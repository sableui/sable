import { createHash } from "node:crypto"
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { afterEach, beforeEach, describe, expect, it } from "vitest"
// @ts-expect-error Plain JS tool shipped with the CLI.
import { claudeStopHook, installAgentSkill, installClaudeStopHook, instructionsBlock } from "../../scripts/agent-setup.mjs"

let scratch: string
let root: string
let packageRoot: string
beforeEach(() => {
	scratch = mkdtempSync(join(tmpdir(), "sable-agent-test-"))
	root = join(scratch, "project")
	packageRoot = join(scratch, "package")
	mkdirSync(root)
	writeFileSync(join(root, "package.json"), "{}")
	mkdirSync(join(packageRoot, "skills/sable/agents"), { recursive: true })
	writeFileSync(join(packageRoot, "skills/sable/SKILL.md"), "packaged instructions")
	mkdirSync(join(packageRoot, "skills/entry"), { recursive: true })
	writeFileSync(join(packageRoot, "skills/entry/SKILL.md"), "Read installed skills/sable/SKILL.md")
	writeFileSync(join(packageRoot, "skills/sable/agents/openai.yaml"), "display_name: Sable")
})
afterEach(() => rmSync(scratch, { recursive: true, force: true }))
describe("agent setup", () => {
	it("installs shared entries and metadata for all hosts, preserves project instructions, and repeats safely", () => {
		writeFileSync(join(root, "AGENTS.md"), "project rules")
		installAgentSkill({ root, packageRoot })
		installAgentSkill({ root, packageRoot })
		expect(readFileSync(join(root, ".agents/skills/sable/agents/openai.yaml"), "utf8")).toContain("Sable")
		const agents = readFileSync(join(root, "AGENTS.md"), "utf8")
		expect(agents.startsWith("project rules\n\n<!-- sable:begin")).toBe(true)
		expect(agents.match(/sable:begin/g)).toHaveLength(1)
		expect(readFileSync(join(root, ".agents/skills/sable/SKILL.md"), "utf8")).toBe("Read installed skills/sable/SKILL.md")
		expect(readFileSync(join(root, ".claude/skills/sable/SKILL.md"), "utf8")).toBe("Read installed skills/sable/SKILL.md")
	})
	it("performs no writes in dry-run mode", () => {
		const result = installAgentSkill({ root, packageRoot, dryRun: true })
		expect(result.instructionsChanged).toEqual(["AGENTS.md", "CLAUDE.md"])
		expect(existsSync(join(root, ".agents"))).toBe(false)
		expect(existsSync(join(root, ".claude"))).toBe(false)
		expect(existsSync(join(root, ".sable"))).toBe(false)
		expect(existsSync(join(root, "AGENTS.md"))).toBe(false)
		expect(existsSync(join(root, "CLAUDE.md"))).toBe(false)
	})
	it("sends every UI request through the skill from the always-loaded project instructions", () => {
		writeFileSync(join(root, "pnpm-lock.yaml"), "")
		installAgentSkill({ root, packageRoot })
		const block = readFileSync(join(root, "CLAUDE.md"), "utf8")
		expect(block).toBe(readFileSync(join(root, "AGENTS.md"), "utf8"))
		expect(block).toContain("load the `sable` skill first")
		expect(block).toContain("`pnpm exec sable check`")
		expect(block.trim().endsWith("<!-- sable:end -->")).toBe(true)
	})
	it("writes the block for the chosen host only, and once when CLAUDE.md imports AGENTS.md", () => {
		installAgentSkill({ root, packageRoot, target: "claude" })
		expect(existsSync(join(root, "AGENTS.md"))).toBe(false)
		expect(readFileSync(join(root, "CLAUDE.md"), "utf8")).toContain("sable:begin")
		rmSync(join(root, "CLAUDE.md"))
		writeFileSync(join(root, "CLAUDE.md"), "@AGENTS.md\n")
		installAgentSkill({ root, packageRoot })
		expect(readFileSync(join(root, "CLAUDE.md"), "utf8")).toBe("@AGENTS.md\n")
		expect(readFileSync(join(root, "AGENTS.md"), "utf8")).toContain("sable:begin")
	})
	it("refreshes its own block under --update, keeps the text around it, and refuses local edits inside it", () => {
		writeFileSync(join(root, "AGENTS.md"), "before\n")
		installAgentSkill({ root, packageRoot, target: "codex" })
		const old = readFileSync(join(root, "AGENTS.md"), "utf8")
		// An older Sable's block: what the receipt recorded, so --update may replace it.
		const older = old.replace("Never rebuild", "Do not rebuild")
		const receipt = JSON.parse(readFileSync(join(root, ".sable/agent-setup.json"), "utf8"))
		receipt.files["AGENTS.md#sable"] = createHash("sha256").update(older.slice(older.indexOf("<!-- sable:begin"), older.indexOf("<!-- sable:end -->") + 18)).digest("hex")
		writeFileSync(join(root, ".sable/agent-setup.json"), JSON.stringify(receipt))
		writeFileSync(join(root, "AGENTS.md"), `${older}after\n`)
		expect(() => installAgentSkill({ root, packageRoot, target: "codex" })).toThrow("Sable block in AGENTS.md differs")
		installAgentSkill({ root, packageRoot, target: "codex", update: true })
		expect(readFileSync(join(root, "AGENTS.md"), "utf8")).toBe(`${old}after\n`)
		writeFileSync(join(root, "AGENTS.md"), old.replace("Never rebuild", "My rule"))
		expect(() => installAgentSkill({ root, packageRoot, target: "codex", update: true })).toThrow("Sable block in AGENTS.md differs")
	})
	it("skips the block on request", () => {
		const result = installAgentSkill({ root, packageRoot, instructions: false })
		expect(result.instructions).toEqual([])
		expect(existsSync(join(root, "AGENTS.md"))).toBe(false)
		expect(existsSync(join(root, "CLAUDE.md"))).toBe(false)
	})
	it("names the workspace package and its runner in a monorepo block", () => {
		writeFileSync(join(root, "pnpm-lock.yaml"), "")
		const app = join(root, "apps", "web")
		mkdirSync(app, { recursive: true })
		writeFileSync(join(app, "package.json"), JSON.stringify({ name: "web" }))
		expect(instructionsBlock({ root, project: app })).toContain("The UI in `apps/web`")
		expect(instructionsBlock({ root, project: app })).toContain("`pnpm --filter web exec sable check`")
	})
	it("refuses a changed file before copying any missing files", () => {
		mkdirSync(join(root, ".agents/skills/sable"), { recursive: true })
		writeFileSync(join(root, ".agents/skills/sable/SKILL.md"), "local rules")
		expect(() => installAgentSkill({ root, packageRoot })).toThrow("Existing skill differs")
		expect(existsSync(join(root, ".agents/skills/sable/agents"))).toBe(false)
		expect(existsSync(join(root, ".claude"))).toBe(false)
	})
	it("requires an update to refresh managed entries but preserves local edits even with update", () => {
		installAgentSkill({ root, packageRoot })
		writeFileSync(join(packageRoot, "skills/entry/SKILL.md"), "Read updated installed instructions")
		expect(() => installAgentSkill({ root, packageRoot })).toThrow("Existing skill differs")
		installAgentSkill({ root, packageRoot, update: true })
		expect(readFileSync(join(root, ".claude/skills/sable/SKILL.md"), "utf8")).toContain("updated")
		writeFileSync(join(root, ".claude/skills/sable/SKILL.md"), "My local rules")
		writeFileSync(join(packageRoot, "skills/entry/SKILL.md"), "Another version")
		expect(() => installAgentSkill({ root, packageRoot, update: true })).toThrow("Existing skill differs")
		expect(readFileSync(join(root, ".agents/skills/sable/SKILL.md"), "utf8")).toBe("Read updated installed instructions")
	})
	it("uses the same discovery directory for Codex and Cursor and supports Claude alone", () => {
		const codex = installAgentSkill({ root, packageRoot, target: "codex" })
		const cursor = installAgentSkill({ root, packageRoot, target: "cursor" })
		expect(cursor.destinations).toEqual(codex.destinations)
		expect(existsSync(join(root, ".claude"))).toBe(false)
		installAgentSkill({ root, packageRoot, target: "claude" })
		expect(existsSync(join(root, ".claude/skills/sable/SKILL.md"))).toBe(true)
	})
	it("does not copy canonical instructions that can become stale after an upgrade", () => {
		installAgentSkill({ root, packageRoot })
		writeFileSync(join(packageRoot, "skills/sable/SKILL.md"), "new workflow")
		installAgentSkill({ root, packageRoot })
		expect(readFileSync(join(root, ".agents/skills/sable/SKILL.md"), "utf8")).not.toContain("packaged instructions")
	})
	it("refuses a linked setup receipt before writing any host entry", () => {
		const outside = join(scratch, "outside")
		mkdirSync(outside)
		symlinkSync(outside, join(root, ".sable"), process.platform === "win32" ? "junction" : "dir")
		expect(() => installAgentSkill({ root, packageRoot })).toThrow("linked destination")
		expect(existsSync(join(root, ".agents"))).toBe(false)
	})
	it("refuses a destination junction instead of writing outside the project", () => {
		const outside = join(scratch, "outside")
		mkdirSync(outside)
		symlinkSync(outside, join(root, ".agents"), process.platform === "win32" ? "junction" : "dir")
		expect(() => installAgentSkill({ root, packageRoot })).toThrow("linked destination")
		expect(existsSync(join(outside, "skills"))).toBe(false)
	})
	it("writes entries at a repository root that resolve Sable through the workspace package", () => {
		writeFileSync(join(packageRoot, "skills/entry/SKILL.md"), `From the target project's dependency context, run:\n\nnode -p "require.resolve('@sableui/react/registry.json')"\n`)
		const app = join(root, "apps", "web")
		mkdirSync(app, { recursive: true })
		writeFileSync(join(app, "package.json"), "{}")
		const result = installAgentSkill({ root, project: app, packageRoot })
		expect(result.project).toBe("apps/web")
		const entry = readFileSync(join(root, ".claude/skills/sable/SKILL.md"), "utf8")
		expect(entry).toContain("`apps/web` package")
		expect(entry).toContain("{ paths: ['apps/web'] }")
		expect(readFileSync(join(root, ".sable/agent-setup.json"), "utf8")).toContain(".claude/skills/sable/SKILL.md")
		expect(existsSync(join(app, ".claude"))).toBe(false)
	})
	it("refuses a root that does not contain the project", () => {
		const elsewhere = join(scratch, "elsewhere")
		mkdirSync(elsewhere)
		expect(() => installAgentSkill({ root: elsewhere, project: root, packageRoot })).toThrow("ancestors")
		expect(existsSync(join(elsewhere, ".claude"))).toBe(false)
	})
	it("prints a Claude Code Stop hook without touching settings, and writes it only when asked", () => {
		writeFileSync(join(root, "pnpm-lock.yaml"), "")
		const hook = claudeStopHook({ root })
		expect(hook.command).toBe("pnpm exec sable check --stop-hook")
		// Stop takes no matcher: hooks.Stop[] → { hooks: [{ type: "command", command }] }.
		expect(hook.settings).toEqual({ hooks: { Stop: [{ hooks: [{ type: "command", command: hook.command, timeout: 300 }] }] } })
		expect(existsSync(join(root, ".claude"))).toBe(false)
		installClaudeStopHook({ root, dryRun: true })
		expect(existsSync(join(root, ".claude"))).toBe(false)
		installClaudeStopHook({ root })
		expect(JSON.parse(readFileSync(join(root, ".claude/settings.json"), "utf8"))).toEqual(hook.settings)
	})
	it("merges the Stop hook into existing settings once, keeping every other key and hook", () => {
		mkdirSync(join(root, ".claude"))
		const existing = { permissions: { allow: ["Bash(ls)"] }, hooks: { Stop: [{ hooks: [{ type: "command", command: "echo done" }] }], PreToolUse: [] } }
		writeFileSync(join(root, ".claude/settings.json"), JSON.stringify(existing))
		installClaudeStopHook({ root })
		const second = installClaudeStopHook({ root })
		expect(second.alreadyPresent).toBe(true)
		const settings = JSON.parse(readFileSync(join(root, ".claude/settings.json"), "utf8"))
		expect(settings.permissions).toEqual(existing.permissions)
		expect(settings.hooks.PreToolUse).toEqual([])
		expect(settings.hooks.Stop).toHaveLength(2)
		expect(settings.hooks.Stop[0]).toEqual(existing.hooks.Stop[0])
	})
	it("refuses settings it cannot parse rather than overwrite them", () => {
		mkdirSync(join(root, ".claude"))
		writeFileSync(join(root, ".claude/settings.json"), "{ not json")
		expect(() => installClaudeStopHook({ root })).toThrow("not valid JSON")
		expect(readFileSync(join(root, ".claude/settings.json"), "utf8")).toBe("{ not json")
	})
	it("runs the hook in the Sable package when the entries live at a repository root", () => {
		const app = join(root, "apps", "web")
		mkdirSync(app, { recursive: true })
		writeFileSync(join(app, "package.json"), JSON.stringify({ name: "@acme/web" }))
		expect(claudeStopHook({ root, project: app }).command).toBe('npm exec --workspace "@acme/web" --no -- sable check --stop-hook --root apps/web')
		writeFileSync(join(root, "pnpm-lock.yaml"), "")
		expect(claudeStopHook({ root, project: app }).command).toBe('pnpm --filter "@acme/web" exec sable check --stop-hook --root apps/web')
		writeFileSync(join(app, "package.json"), "{}")
		expect(claudeStopHook({ root, project: app }).command).toBe("pnpm exec sable check --stop-hook --root apps/web")
	})
	it("keeps the hook command free of shell syntax, so Git Bash and PowerShell 5.1 both run it", () => {
		for (const lock of ["pnpm-lock.yaml", "yarn.lock", "package-lock.json"]) {
			writeFileSync(join(root, lock), "")
			const app = join(root, "packages", "my app")
			mkdirSync(app, { recursive: true })
			writeFileSync(join(app, "package.json"), JSON.stringify({ name: "@acme/app" }))
			for (const { command } of [claudeStopHook({ root }), claudeStopHook({ root, project: app })]) {
				expect(command, command).not.toMatch(/&&|\|\||;|\$|`|\bcd\b/)
				expect(command).toContain("sable check --stop-hook")
			}
			rmSync(join(root, lock))
		}
		const odd = join(root, "apps", "a&b")
		mkdirSync(odd, { recursive: true })
		writeFileSync(join(odd, "package.json"), "{}")
		expect(() => claudeStopHook({ root, project: odd })).toThrow("Add the hook by hand")
	})
})
