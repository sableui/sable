/**
 * How a workspace app consumes @sableui/react — shared by apps/docs and
 * any other workspace consumer so they cannot drift.
 *
 * Inside the workspace the package's `exports` point at `src/`, so an app here
 * would otherwise only ever run on source, never on what a user installs.
 * Anything that breaks only once built (a missing export path, CSS not copied
 * to dist, a class Tailwind cannot find in the compiled JS, a wrong .d.ts)
 * would be invisible to the apps that use the library most. So each app has
 * two modes:
 *
 * - source   — the package's src, for the edit loop (`dev`).
 * - consumer — the published dist, wired exactly as the README tells a user
 *              (`build`): CSS from the published export map, `@source` over
 *              `dist/**\/*.{js,mjs}`, JS resolved through `publishConfig.exports`
 *              (an unpublished subpath is a build error — the app's import
 *              boundary), types checked against the shipped .d.ts.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const NAME = "@sableui/react"
export const PKG = join(dirname(fileURLToPath(import.meta.url)), "..", "packages", "sable")

function readPublished() {
	const pkg = JSON.parse(readFileSync(join(PKG, "package.json"), "utf8"))
	return pkg.publishConfig?.exports ?? {}
}

/** Forward-slash relative path, as CSS and tsconfig expect on every OS. */
const rel = (from, to) => relative(from, to).split("\\").join("/")
const target = (entry) => (typeof entry === "string" ? entry : entry.default)

/**
 * Vite plugin for consumer mode: resolve every import of @sableui/react
 * through the PUBLISHED export map, to the built dist. A subpath that is not
 * published fails the build, because a user could not import it either.
 */
export function sableAsPublished() {
	const published = readPublished()
	return {
		name: "sable-as-published",
		enforce: "pre",
		resolveId(id) {
			if (id !== NAME && !id.startsWith(`${NAME}/`)) return null
			const sub = id === NAME ? "." : `./${id.slice(NAME.length + 1)}`
			const entry = published[sub]
			if (!entry) {
				this.error(`"${id}" is not a published entry point of ${NAME} (publishConfig.exports). A user could not import it; neither may this app.`)
			}
			return join(PKG, target(entry))
		},
	}
}

/**
 * Write the app's generated Sable wiring for a mode.
 *
 * @param {object} opts
 * @param {string} opts.appDir   the app's root (where tsconfig.json lives)
 * @param {"source"|"consumer"} opts.mode
 * @param {string[]} opts.css    published CSS subpaths the app imports, e.g. ["./styles.css"]
 *
 * Writes `<appDir>/src/generated/sable.css` (the app's CSS imports it) and, in
 * consumer mode, `<appDir>/tsconfig.consumer.json`. Both are gitignored.
 */
export function writeSableMode({ appDir, mode, css, separateCss = {} }) {
	if (mode !== "source" && mode !== "consumer") throw new Error(`sable mode must be "source" or "consumer", got "${mode}"`)
	const generated = join(appDir, "src", "generated")
	mkdirSync(generated, { recursive: true })
	const published = readPublished()
	let out

	if (mode === "source") {
		out = [
			"/* Generated by scripts/sable-consumer.mjs (source) — the package's src, for the dev loop. */",
			...css.map((sub) => `@import "${NAME}/${sub.slice(2)}";`),
			`@source "${rel(generated, join(PKG, "src"))}/**/*.{ts,tsx}";`,
		]
	} else {
		if (!existsSync(join(PKG, "dist", "index.js"))) {
			throw new Error("consumer mode needs the built package. Run `pnpm build` at the repo root first.")
		}
		out = [
			"/* Generated by scripts/sable-consumer.mjs (consumer) — the published dist, wired as the README says. */",
			...css.map((sub) => {
				if (!published[sub]) throw new Error(`"${sub}" is not in publishConfig.exports — a user could not import it.`)
				return `@import "${rel(generated, join(PKG, target(published[sub])))}";`
			}),
			`@source "${rel(generated, join(PKG, "dist"))}/**/*.{js,mjs}";`,
		]

		// Every published JS entry → its shipped .d.ts.
		const paths = {}
		for (const [sub, entry] of Object.entries(published)) {
			if (typeof entry === "string" || !entry.types) continue
			paths[sub === "." ? NAME : `${NAME}/${sub.slice(2)}`] = [rel(appDir, join(PKG, entry.types))]
		}
		const tsconfig = {
			$comment:
				"Generated by scripts/sable-consumer.mjs. Type-checks the app against the SHIPPED .d.ts files, as a user's app would see them. Gitignored.",
			extends: "./tsconfig.json",
			compilerOptions: { paths },
		}
		writeFileSync(join(appDir, "tsconfig.consumer.json"), `${JSON.stringify(tsconfig, null, "\t")}\n`)
	}

	writeFileSync(join(generated, "sable.css"), `${out.join("\n")}\n`)
	// Keep optional platform CSS out of the web host's generated stylesheet.
	for (const [name, subpaths] of Object.entries(separateCss)) {
		if (!/^[\w-]+\.css$/.test(name)) throw new Error(`Invalid generated CSS filename: ${name}`)
		const imports = subpaths.map(sub => {
			if (!published[sub]) throw new Error(`"${sub}" is not a published CSS entry.`)
			return mode === "source" ? `@import "${NAME}/${sub.slice(2)}";` : `@import "${rel(generated, join(PKG, target(published[sub])))}";`
		})
		writeFileSync(join(generated, name), `${imports.join("\n")}\n`)
	}
	return mode === "source" ? "src (dev)" : "dist (as a user)"
}

/** CLI helper for an app's tiny sable-mode.mjs wrapper. */
export function runSableModeCli({ app, appDir, css, separateCss }) {
	const mode = process.argv[2]
	try {
		const where = writeSableMode({ appDir, mode, css, separateCss })
		console.log(`[sable-mode] ✓ ${app} consumes ${NAME} from ${where}.`)
	} catch (error) {
		console.error(`[sable-mode] ✗ ${error.message}`)
		console.error("[sable-mode] usage: node scripts/sable-mode.mjs source|consumer")
		process.exit(1)
	}
}
