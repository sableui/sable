/**
 * The library's pre-paint theme boot script (`sableThemeScript` from
 * @sableui/react), inlined at the top of index.html's <head>. Without it the
 * page painted the hard-coded dark Sable until React's passive effects applied
 * the reader's stored mode and preset: a dark flash on every load for anyone
 * on light or on another preset.
 *
 *   node scripts/theme-boot.mjs          rewrite the block in index.html
 *   node scripts/theme-boot.mjs --check  exit 1 if index.html is stale
 *
 * The block sits between the `sable-theme-boot` markers and is the library's
 * output verbatim, so it never drifts from what SableThemeProvider does. The
 * options must match ThemeProvider's (src/theme.tsx): the same storage keys
 * and default preference, or script and provider disagree about which mode
 * to open in. Only the docs entry gets it; the iPhone frames take their look
 * from the host page.
 *
 * `--check` runs in the app's `typecheck`, `build` and `build:source`
 * scripts, so a library change to sableThemeScript fails the docs until the
 * block is regenerated. It always reads the package's `src` (the workspace
 * `exports`, which consumer mode does not touch), so it behaves the same in
 * source and consumer mode and needs no built `dist`.
 *
 * `sableThemeBoot()` is the same thing as a Vite plugin, for wiring into
 * vite.config.ts instead of committing the block (not wired: the committed
 * block plus the check keeps the HTML readable and the build deterministic).
 */
import { readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { runnerImport } from "vite"

const OPTIONS = { defaultPreference: "dark", colorStorageKey: "sable-docs-theme", themeStorageKey: "sable-docs-theme-id" }
const root = resolve(import.meta.dirname, "..")
const START = "<!-- sable-theme-boot: generated by scripts/theme-boot.mjs from sableThemeScript() -->"
const END = "<!-- /sable-theme-boot -->"

/** The script text, loaded through Vite's module runner so the package's TypeScript source works. */
export async function themeBootScript(at = root) {
	const { module } = await runnerImport("@sableui/react/themes", { root: at, configFile: false, logLevel: "silent" })
	return module.sableThemeScript(OPTIONS)
}

export function sableThemeBoot() {
	let script = null
	return {
		name: "sable-docs-theme-boot",
		async configResolved(config) {
			script = await themeBootScript(config.root)
		},
		transformIndexHtml: {
			order: "pre",
			handler(html, ctx) {
				if (!script || html.includes(START) || !/(^|[\\/])index\.html$/.test(ctx.filename)) return html
				return { html, tags: [{ tag: "script", children: script, injectTo: "head-prepend" }] }
			},
		},
	}
}

if (import.meta.url === `file:///${process.argv[1]?.replace(/\\/g, "/")}` || process.argv[1]?.endsWith("theme-boot.mjs")) {
	const file = resolve(root, "index.html")
	const html = readFileSync(file, "utf8")
	const eol = html.includes("\r\n") ? "\r\n" : "\n"
	const block = `${START}${eol}\t\t<script>${await themeBootScript()}</script>${eol}\t\t${END}`
	const pattern = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`)
	if (!pattern.test(html)) throw new Error("index.html has no sable-theme-boot block")
	const next = html.replace(pattern, block)
	if (process.argv.includes("--check")) {
		if (next !== html) {
			console.error("index.html's theme boot script is stale: run node scripts/theme-boot.mjs")
			process.exit(1)
		}
		console.log("index.html theme boot script is current.")
	} else if (next !== html) {
		writeFileSync(file, next)
		console.log("Updated index.html's theme boot script.")
	} else console.log("index.html theme boot script is current.")
}
